    SUM(TRIM(Customer_ID) = '') AS Customer_ID_Blanks,
    SUM(TRIM(Gender) = '') AS Gender_Blanks,
    SUM(Age IS NULL) AS Age_Blanks,
    SUM(TRIM(Married) = '') AS Married_Blanks,
    SUM(TRIM(State) = '') AS State_Blanks,
    SUM(Number_of_Referrals IS NULL) AS Number_of_Referrals_Blanks,
    SUM(Tenure_in_Months IS NULL) AS Tenure_in_Months_Blanks,
    SUM(TRIM(Value_Deal) = '') AS Value_Deal_Blanks,
    SUM(TRIM(Phone_Service) = '') AS Phone_Service_Blanks,
    SUM(TRIM(Multiple_Lines) = '') AS Multiple_Lines_Blanks, 
    SUM(TRIM(Internet_Service) = '') AS Internet_Service_Blanks,
    SUM(TRIM(Internet_Type) = '') AS Internet_Type_Blanks,
    SUM(TRIM(Online_Security) = '') AS Online_Security_Blanks,
    SUM(TRIM(Online_Backup) = '') AS Online_Backup_Blanks,
    SUM(TRIM(Device_Protection_Plan) = '') AS Device_Protection_Plan_Blanks,
    SUM(TRIM(Premium_Support) = '') AS Premium_Support_Blanks,
    SUM(TRIM(Streaming_TV) = '') AS Streaming_TV_Blanks,
    SUM(TRIM(Streaming_Movies) = '') AS Streaming_Movies_Blanks,
    SUM(TRIM(Streaming_Music) = '') AS Streaming_Music_Blanks,
    SUM(TRIM(Unlimited_Data) = '') AS Unlimited_Data_Blanks,
    SUM(TRIM(Contract) = '') AS Contract_Blanks,
    SUM(TRIM(Paperless_Billing) = '') AS Paperless_Billing_Blanks,
    SUM(TRIM(Payment_Method) = '') AS Payment_Method_Blanks,
    SUM(Monthly_Charge IS NULL) AS Monthly_Charge_Blanks,
    SUM(Total_Charges IS NULL) AS Total_Charges_Blanks,
    SUM(Total_Refunds IS NULL) AS Total_Refunds_Blanks,
    SUM(Total_Extra_Data_Charges IS NULL) AS Total_Extra_Data_Charges_Blanks,
    SUM(Total_Long_Distance_Charges IS NULL) AS Total_Long_Distance_Charges_Blanks,
    SUM(Total_Revenue IS NULL) AS Total_Revenue_Blanks,
    SUM(TRIM(Customer_Status) = '') AS Customer_Status_Blanks,
    SUM(TRIM(Churn_Category) = '') AS Churn_Category_Blanks,
    SUM(TRIM(Churn_Reason) = '') AS Churn_Reason_Blanks
FROM churn;